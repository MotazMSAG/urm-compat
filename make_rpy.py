"""
Builds urm_plus.rpy - the whole add-on as one file a player drops into a
game's game/ folder next to URM's own archive.

    python make_rpy.py [output path]

No game and no Ren'Py are needed: this only writes text. The result holds

  * a small init -999 block that patches URM's screens as URM loads them -
    every tweak from ui_tweaks.py, applied in memory to the text URM reads
    from its own, untouched archive
  * game_fixes.rpy, unchanged

Each game compiles the file with its own engine on first launch, so there is
no per-engine build and no archive to rebuild - and URM can update itself:
a tweak whose anchor URM changed is skipped and logged, the rest still apply.
"""

from __future__ import print_function

import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import ui_tweaks  # noqa


def literal(data):
    """A bytes literal both Python 2 and 3 read the same way, ASCII only."""

    out = ["b'"]
    for byte in bytearray(data):
        ch = chr(byte)
        if ch == "\\":
            out.append("\\\\")
        elif ch == "'":
            out.append("\\'")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\n":
            out.append("\\n")
        elif 32 <= byte < 127:
            out.append(ch)
        else:
            out.append("\\x%02x" % byte)
    out.append("'")
    return "".join(out)


HEADER = '''\
# URM+ - an add-on for Universal Ren'Py Mod (URM) by 0x52
#
# URM is 0x52's work: https://0x52.dev - this file contains none of it, and
# needs it. Put this file in a game's game/ folder next to URM's own
# 0x52_URM.rpa. To remove it, delete urm_plus.rpy and urm_plus.rpyc.
# Coming from URM Compat (the old name)? Delete urm_compat.rpy and .rpyc.
#
# Generated by make_rpy.py from game_fixes.rpy and ui_tweaks.py:
# https://github.com/MotazMSAG/urm-plus - edit those, not this.


# ---------------------------------------------------------------------------
# URM's screens, patched as URM loads them
# ---------------------------------------------------------------------------
#
# URM reads each of its screen files (.x52) as text out of its own archive and
# hands it to renpy.load_string, all through x52MF2.loadFile, at init 999.
# x52MF2 is defined at init -1000, so wrapping loadFile here, at -999, puts
# every edit below between the archive and the parser. The archive itself is
# never touched.
#
# Each edit replaces one passage that must occur exactly once; `old` lists
# the passage as URM ships it plus earlier forms. One that does not match -
# after a URM update, say - is skipped and logged, and the file loads with
# the rest. If a patched file fails to parse, URM's original is loaded
# instead, so the add-on can never stop URM from starting.

init -999 python:

    _urmc_x52_tweaks = (
'''

FOOTER = '''\
    )

    _urmc_x52_report = python_list()

    def _urmc_x52_patch(path, data):
        for name, target, check, olds, new in _urmc_x52_tweaks:
            if target != path:
                continue
            if check and check in data:
                continue
            match = None
            for old in olds:
                if data.count(old) == 1:
                    match = old
                    break
            if match is None:
                _urmc_x52_report.append((name, "not found - URM probably changed it"))
                print("URM+: skipped \\"%s\\" - URM probably changed %s" % (name, path))
                continue
            data = data.replace(match, new)
            _urmc_x52_report.append((name, None))
        return data

    def _urmc_x52_install():
        # In an init python block the store is this block's globals, and
        # x52MF2 - a store module of URM's - is one of them.
        mf = globals().get("x52MF2") or getattr(renpy.store, "x52MF2", None)
        original = getattr(mf, "loadFile", None)
        if original is None or getattr(original, "_urmc_original", None) is not None:
            return

        paths = python_set()
        for item in _urmc_x52_tweaks:
            paths.add(item[1])

        def loadFile(fullFn, modName, mfPath=None):
            if fullFn not in paths:
                return original(fullFn, modName, mfPath)
            source = renpy.loadable(fullFn)
            transformed = renpy.loadable(fullFn + "t")
            if not (source or transformed):
                return original(fullFn, modName, mfPath)
            try:
                data = renpy.loader.load(fullFn + "t" if transformed else fullFn).read()
                text = _urmc_x52_patch(fullFn, data).decode("utf-8")
                if source:
                    text = text.replace("_x52ModName_", modName)
                    if mfPath:
                        text = text.replace("_x52MFPath_", mfPath)
                if renpy.load_string(text, fullFn) is None:
                    raise Exception(renpy.get_parse_errors())
            except Exception as error:
                print("URM+: %s did not load patched, loading URM's own (%s)" % (fullFn, error))
                return original(fullFn, modName, mfPath)

        loadFile._urmc_original = original
        mf.loadFile = loadFile

    try:
        _urmc_x52_install()
    except Exception as error:
        print("URM+: URM's screens left unpatched (%s)" % (error,))


'''


def build():
    parts = [HEADER]
    for item in ui_tweaks.TWEAKS:
        olds = ", ".join(literal(o) for o in item["old"])
        parts.append("        (%r,\n         %r,\n         %s,\n         (%s,),\n         %s),\n" % (
            str(item["name"]), str(item["path"]), literal(item["check"]), olds, literal(item["new"])))
    parts.append(FOOTER)
    fixes = io.open(os.path.join(HERE, "game_fixes.rpy"), encoding="utf-8").read()
    parts.append(fixes.replace("\r\n", "\n"))
    return "".join(parts)


def main(argv):
    output = os.path.abspath(argv[1]) if len(argv) > 1 else os.path.join(HERE, "dist", "urm_plus.rpy")
    if not os.path.isdir(os.path.dirname(output)):
        os.makedirs(os.path.dirname(output))
    text = build()
    with io.open(output, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("Wrote %s  (%d tweaks, %.0f KB)" % (output, len(ui_tweaks.TWEAKS), os.path.getsize(output) / 1024.0))
    print("Put it in a game's game/ folder next to URM's 0x52_URM.rpa.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
