"""
Checks urm_compat.rpy - the one-file install - against URM's real archive.

    <a game's bundled python> -I -B check_runtime.py <that game folder> <0x52_URM.rpa>

The file is generated by make_rpy.py, parsed with the game's own Ren'Py, and
its init -999 block is run against a stand-in for URM's loader that serves the
real archive. Every screen it hands to renpy.load_string must be exactly what
the archive build produces with ui_tweaks.apply() - the same edits, whether
they are baked into an archive or applied as URM loads.
"""

from __future__ import print_function

import io
import os
import shutil
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLKIT = os.path.dirname(HERE)
sys.path.insert(0, TOOLKIT)
sys.path.insert(0, HERE)

if len(sys.argv) < 3:
    print(__doc__)
    sys.exit(2)

base = os.path.abspath(sys.argv[1])
rpa = os.path.abspath(sys.argv[2])

import make_rpy  # noqa
import ui_tweaks  # noqa

text = make_rpy.build()

os.chdir(base)
sys.path.insert(0, base)
import renpy  # noqa
renpy.import_all()
renpy.config.basedir = base
renpy.config.gamedir = os.path.join(base, "game")
renpy.sl2.slparser.init()


class FakeScript(object):
    record_pycode = False
    all_pycode = []
    serial = 0

    def __getattr__(self, name):
        return None


renpy.game.script = FakeScript()
renpy.game.log = type("L", (), {"mutated": {}})()
if not renpy.game.contexts:
    renpy.game.contexts = [type("C", (), {"init_phase": True})()]

failures = []


def check(name, got, want):
    if got == want:
        print("pass  %s" % name)
    else:
        failures.append(name)
        print("FAIL  %s" % name)
        if isinstance(want, (bytes, type(u""))) and len(want) > 200:
            print("        (long text differs)")
        else:
            print("        expected %r" % (want,))
            print("        got      %r" % (got,))


check("the file is plain ASCII apart from game_fixes.rpy's icons",
      all(ord(c) < 128 for c in text[:text.index("init 999 python:")]), True)

folder = tempfile.mkdtemp(prefix="urm_check_runtime_")
try:
    path = os.path.join(folder, "urm_compat.rpy")
    io.open(path, "w", encoding="utf-8", newline="\n").write(text)
    statements = renpy.parser.parse(path)
finally:
    shutil.rmtree(folder, ignore_errors=True)
check("it parses with this game's Ren'Py", statements is not None, True)
if statements:
    others = [type(n).__name__ for n in statements
              if not isinstance(n, (renpy.ast.Init, renpy.ast.Return))]
    check("and holds nothing but init blocks", others, [])

# --- the loader wrapper, against the real archive ---------------------------

contents = run_tests_read = None
import run_tests  # noqa
contents = run_tests.read_archive(rpa)

expected = dict(contents)
ui_tweaks.apply(expected)

body = text.split("init -999 python:", 1)[1].split("\ninit 999 python:", 1)[0]
lines = []
for line in body.split("\n"):
    lines.append(line[4:] if line.startswith("    ") else line)
body = "\n".join(lines)

loaded = {}
originals = []


class Loader(object):
    @staticmethod
    def load(name):
        return io.BytesIO(contents[name])


class MF2(object):
    pass


mf = MF2()


def original(fullFn, modName, mfPath=None):
    originals.append(fullFn)


mf.loadFile = original


class StoreRenpy(object):
    loader = Loader()
    store = type("S", (), {"x52MF2": mf})()
    fail_parse = False

    @staticmethod
    def loadable(name):
        return name in contents

    @classmethod
    def load_string(cls, s, filename):
        if cls.fail_parse:
            return None
        loaded[filename] = s
        return []

    @staticmethod
    def get_parse_errors():
        return "stand-in parse error"


ns = {"renpy": StoreRenpy, "x52MF2": mf, "python_list": list, "python_set": set,
      "python_dict": dict, "__name__": "urm_runtime_check"}
exec(compile(body, "urm_compat.rpy", "exec"), ns)

screens = sorted(n for n in contents if n.startswith("0x52-URM/screens/") and n.endswith(".x52"))
for name in screens:
    mf.loadFile(name, "x52URM")

patched = sorted(set(t["path"] for t in ui_tweaks.TWEAKS))
check("every patched screen went through the wrapper", sorted(loaded), patched)
check("the others were left to URM's own loader",
      sorted(originals), sorted(n for n in screens if n not in patched))
same = []
for name in patched:
    want = expected[name].decode("utf-8").replace("_x52ModName_", "x52URM")
    same.append(loaded.get(name) == want)
check("each is exactly what the archive build bakes in", same, [True] * len(patched))
check("no edit was skipped", [r for r in ns["_urmc_x52_report"] if r[1] is not None], [])
check("installing twice wraps once", (ns["_urmc_x52_install"](), mf.loadFile._urmc_original is original), (None, True))

del originals[:]
StoreRenpy.fail_parse = True
mf.loadFile(patched[0], "x52URM")
check("a patched screen that fails to parse falls back to URM's own", originals, [patched[0]])

print()
print("all passed" if not failures else "%d FAILED" % len(failures))
sys.exit(1 if failures else 0)
